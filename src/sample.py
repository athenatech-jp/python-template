def add(a: int, b: int) -> int:
    """
    Add two numbers together

    Parameters
    ----------
    a : int
        The first number
    b : int
        The second number

    Returns
    -------
    int
        The sum of the two numbers
    """
    return a + b


def subtract(a: int, b: int) -> int:
    """
    Subtract two numbers

    Args:
        a: The first number
        b: The second number

    Returns:
        The difference between the two numbers
    """
    return a - b
